/**
 * Accessor for extended domain & telemetry colors.
 */
val MaterialTheme.extendedColors: BlockExtendedColors
    @Composable
    @ReadOnlyComposable
    get() = LocalBlockExtendedColors.current

/**
 * Accessor for standard design system spacing tokens.
 */
val MaterialTheme.spacing: BlockSpacing
    @Composable
    @ReadOnlyComposable
    get() = LocalBlockSpacing.current

@Composable
fun BlockTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Set default dynamicColor to false to maintain the bespoke Kinetic Apex design language
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    val extendedColors = if (darkTheme) DarkExtendedColors else LightExtendedColors
    val spacing = BlockSpacing()

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            if (window != null) {
                val insetsController = WindowCompat.getInsetsController(window, view)
                insetsController.isAppearanceLightStatusBars = !darkTheme
                insetsController.isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    CompositionLocalProvider(
        LocalBlockExtendedColors provides extendedColors,
        LocalBlockSpacing provides spacing
    ) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = Typography,
            shapes = Shapes,
            content = content
        )
    }
}